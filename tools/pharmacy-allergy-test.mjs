import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {medicineAllergyConflicts as check} from '../server/allergy-safety.js';
const allergy=[{substance:'Penicillin',severity:'moderate'}];
assert.equal(check(allergy,[{name:'TEST ONLY — Penicillin'}]).length,1);
assert.equal(check(allergy,[{name:'Brand',generic:'PENICILLIN'}]).length,1);
assert.equal(check(allergy,[{name:'Combination',composition:'[{"generic":"Penicillin","strength":""}]'}]).length,1);
assert.equal(check(allergy,[{name:'Pencil',generic:''}]).length,0);
assert.equal(check(allergy,[{name:'Penicillinium'}]).length,0);
assert.equal(check([],[{name:'Penicillin'}]).length,0);
process.env.SURELY_DATA=fs.mkdtempSync(path.join(os.tmpdir(),'hms-allergy-test-'));
const {insert,one,db}=await import('../server/db.js');
const {dispense}=await import('../server/routes/pharmacy.js');
const patient_id=insert('patients',{uhid:'TEST1',name:'Synthetic allergy test',gender:'Male'});
insert('allergies',{patient_id,substance:'Penicillin',severity:'moderate'});
const medicine_id=insert('medicines',{code:'TEST-PEN',name:'TEST Penicillin',generic:'Penicillin',schedule:'OTC'});
const batch_id=insert('medicine_batches',{medicine_id,batch_no:'TEST',expiry:'2030-12-31',location:'OP',qty:5,mrp:10,purchase_rate:5});
const before=one('SELECT count(*) FROM bills');
assert.throws(()=>dispense({user:{id:1,role:'admin'}},{patient_id,items:[{medicine_id,batch_id,qty:1}]}),e=>e.http===409&&e.message==='medicine_allergy_conflict'&&e.extra.conflicts.length===1);
assert.equal(one('SELECT count(*) FROM bills'),before);
assert.equal(one('SELECT qty FROM medicine_batches WHERE id=?',batch_id),5);
assert.equal(one('SELECT count(*) FROM stock_moves'),0);
db.close();
console.log('PASS: name/generic/composition allergy matching; unrelated names allowed; backend blocks with no bill or stock mutation.');
